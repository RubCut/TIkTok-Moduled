package dev.moduled.api;

import android.content.Context;
import java.io.File;

/**
 * Всё, что платформа передаёт модулю (ТЗ §9). Объект живёт в пределах одного
 * процесса и одного запуска; сохранять его между запусками бессмысленно.
 */
public interface ModuleContext {

    /** Версия контракта SDK, которую реализует этот интерфейс. */
    int API_VERSION = 1;

    /** Контекст приложения хоста (не контекст модуля и не TModules). */
    Context hostContext();

    /** ClassLoader хоста: нужен для поиска классов целевого приложения. */
    ClassLoader hostClassLoader();

    /** ClassLoader самого модуля: отделён от других модулей (RUN-05). */
    ClassLoader moduleClassLoader();

    /** Постоянный ID модуля из внутреннего манифеста. */
    String moduleId();

    /** Человекочитаемая версия модуля. */
    String moduleVersion();

    /** Целая версия для сравнения обновлений (ТЗ §13.3). */
    long moduleVersionCode();

    /** Версия контракта SDK, с которой собран модуль. */
    int apiVersion();

    /** Версия runtime, исполняющего модуль. */
    String runtimeVersion();

    /** Имя текущего процесса хоста. */
    String processName();

    /** Является ли процесс основным: в прототипе поддерживается только он (ТЗ §8.1). */
    boolean isMainProcess();

    /**
     * Приватный каталог рабочих данных модуля (ТЗ §9, CFG-10).
     * Каталог создаётся платформой; он не является конфигом и не синхронизируется
     * обратно в менеджер.
     */
    File dataDirectory();

    /**
     * Снимок текстового конфига на момент старта процесса (ТЗ §12 CFG-09).
     * Только чтение: изменение локальной копии не синхронизируется обратно (CFG-10).
     */
    ConfigSnapshot config();

    /** Журналирование с автоматической пометкой ID модуля (ТЗ §22). */
    ModuleLogger log();

    /** Hook API с явным описанием результата и ошибок (ТЗ §9.1). */
    HookApi hooks();

    /** Сведения о версии хоста и поддерживаемом версионном адаптере. */
    HostInfo host();

    /**
     * Запрос программного перезапуска хоста (ТЗ §19). Перезапуск best-effort:
     * ОС может запретить фоновый старт, поэтому пользователь заранее
     * предупреждается о возможной необходимости открыть приложение вручную.
     */
    RestartResult requestRestart(String reason);
}
