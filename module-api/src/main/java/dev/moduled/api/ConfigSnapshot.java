package dev.moduled.api;

/**
 * Согласованный снимок текстового конфига модуля (ТЗ §12).
 *
 * <p>Содержимое непрозрачно для платформы: это может быть JSON, INI, TOML,
 * собственный синтаксис или обычный текст (CFG-02). Платформа не делает
 * {@code trim()}, не форматирует, не нормализует переводы строк и не добавляет
 * финальный перевод строки (CFG-03), поэтому модуль обязан сам решать, как
 * интерпретировать байты, включая BOM и отсутствие финального newline.</p>
 */
public interface ConfigSnapshot {

    /** Точные байты файла в кодировке UTF-8. */
    byte[] bytes();

    /** Точные байты, декодированные как UTF-8, без каких-либо преобразований. */
    String text();

    /** SHA-256 точных байтов — для сверки с менеджером и диагностикой. */
    String sha256();

    /** Поколение снимка, из которого взят конфиг (ТЗ §20.2). */
    long generation();

    /** Пустой файл допустим (CFG-02). */
    boolean isEmpty();
}
