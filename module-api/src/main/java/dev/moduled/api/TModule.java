package dev.moduled.api;

/**
 * Контракт точки входа модуля (ТЗ §9, §10.1).
 *
 * <p>Класс, указанный в {@code entrypoint} внутреннего манифеста, обязан иметь
 * публичный конструктор без аргументов и реализовывать этот интерфейс. Runtime
 * вызывает {@link #onLoad(ModuleContext)} один раз на процесс и только после
 * всех проверок: safe mode, целостность снимка, формат и совместимость (RUN-02).</p>
 *
 * <p>Модуль исполняется с возможностями процесса хоста. Раздельный ClassLoader
 * не создаёт sandbox (ТЗ §14.1): ответственность за последствия кода несут
 * автор модуля и пользователь, который его включил.</p>
 */
public interface TModule {

    /**
     * Точка входа. Исключение, брошенное до установки хуков, считается ошибкой
     * запуска модуля: модуль помечается ошибочным, остальные модули продолжают
     * загрузку, если целостность runtime не нарушена (RUN-07).
     *
     * <p>Исключение, брошенное ПОСЛЕ установки хуков, не является чистым
     * откатом (RUN-08): хуки остаются установленными до перезапуска процесса.</p>
     */
    void onLoad(ModuleContext context) throws Exception;

    /**
     * Best-effort уведомление о выгрузке. Гарантии полного отката всех действий
     * модуля платформа не даёт (ТЗ §3.2, RUN-10): выключение модуля действует на
     * следующий запуск процесса, а уже загруженный код не считается выгруженным.
     */
    default void onUnload() {
        // По умолчанию модуль не выполняет действий при выгрузке.
    }
}
